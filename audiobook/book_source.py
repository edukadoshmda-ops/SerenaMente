("3. Entendendo a ansiedade", """
## O que é

Sentir ansiedade é normal. Ela nos prepara para desafios. O problema é quando ela se torna excessiva, constante e desproporcional, atrapalhando a vida. Aí falamos em transtorno de ansiedade.

## Formas mais comuns

- Transtorno de Ansiedade Generalizada, o TAG: preocupação constante com várias coisas ao mesmo tempo.
- Síndrome do pânico: crises súbitas de medo intenso com sintomas físicos fortes.
- Fobia social: medo intenso de ser julgado ou humilhado.
- Fobias específicas, TOC, estresse pós-traumático, entre outros.

## Sinais físicos

Coração acelerado, falta de ar, tremores, suor, tontura, formigamento, nó na garganta, dor no estômago, tensão muscular, insônia.

## Sinais emocionais e mentais

Pensamentos acelerados, sensação de perigo iminente, medo de perder o controle ou "enlouquecer", dificuldade de relaxar, irritabilidade, catastrofização: "e se der tudo errado?"

## A crise de pânico não mata

Durante uma crise, o corpo entra em modo de alarme, mas ela passa, geralmente em 10 a 30 minutos. Saber disso já ajuda a atravessá-la.

## Técnica rápida para crises: 5-4-3-2-1

Identifique ao seu redor:

- 5 coisas que você vê.
- 4 coisas que você pode tocar.
- 3 sons que você ouve.
- 2 cheiros que você sente.
- 1 sabor na sua boca.

Isso traz sua mente de volta para o presente.
"""),

